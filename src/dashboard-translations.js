/** @typedef {ReturnType<typeof createDashboardI18n> & {apply: (root: ParentNode) => void}} DashboardI18n */

/** @param {Document} document @param {Window & {RelayI18n?: DashboardI18n, RelayStorage?: Storage}} window @param {typeof createDashboardI18n} factory @param {Parameters<typeof createDashboardI18n>[0]} catalogs */
function bootDashboardI18n(document, window, factory, catalogs) {
  /** @type {Storage|null} */
  var storage = null;
  try { storage = window.localStorage; } catch {}
  /** @type {Record<string, string|null>} */
  var memory = Object.create(null);
  var browserStorage = {
    /** @param {string} key */
    getItem: function (key) {
      if (Object.hasOwn(memory, key)) return memory[key];
      try { return storage?.getItem(key) ?? null; } catch { return null; }
    },
    /** @param {string} key @param {string} value */
    setItem: function (key, value) {
      memory[key] = String(value);
      try { storage?.setItem(key, String(value)); } catch {}
    },
    /** @param {string} key */
    removeItem: function (key) {
      memory[key] = null;
      try { storage?.removeItem(key); } catch {}
    }
  };
  window.RelayStorage = /** @type {Storage} */ (browserStorage);
  var i18n = /** @type {DashboardI18n} */ (factory(catalogs, browserStorage));
  i18n.apply = function (root) {
    root.querySelectorAll('[data-i18n]').forEach(function (element) {
      element.textContent = i18n.t(element.getAttribute('data-i18n') || '');
    });
    ['placeholder', 'title', 'aria-label'].forEach(function (attribute) {
      root.querySelectorAll('[data-i18n-' + attribute + ']').forEach(function (element) {
        element.setAttribute(attribute, i18n.t(element.getAttribute('data-i18n-' + attribute) || ''));
      });
    });
  };
  function refresh() {
    document.documentElement.lang = i18n.locale();
    i18n.apply(document);
    document.querySelectorAll('[data-locale-picker]').forEach(function (element) {
      /** @type {HTMLSelectElement} */ (element).value = i18n.locale();
    });
  }
  document.querySelectorAll('[data-locale-picker]').forEach(function (element) {
    element.addEventListener('change', function () { i18n.setLocale(/** @type {HTMLSelectElement} */ (element).value); });
  });
  window.RelayI18n = i18n;
  i18n.onChange(refresh);
  refresh();
}

